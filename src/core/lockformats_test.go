// yarn.lock goes through the same triage as package-lock.json: uuid is only pulled in by the dev tool.
func TestScanYarnLock(t *testing.T) {
	root := t.TempDir()
	writeFiles(t, root, map[string]string{"yarn.lock": yarnClassicLock, "package.json": demoManifest, "src/index.js": `import kit from '@scope/kit';`})

	server := uuidOSV()
	defer server.Close()

	report, err := Scan(Options{Directory: root, OSV: &OSV{BaseURL: server.URL, Client: server.Client()}})
	if err != nil {
		t.Fatal(err)
	}

	if report.Ecosystem != EcosystemNPM || len(report.Findings) != 1 {
		t.Fatalf("report = %+v", report)
	}

	f := report.Findings[0]
	if f.Package != "uuid" || f.Shipped || f.Verdict != VerdictNotShipped || !reflect.DeepEqual(f.Via, []string{"vitest", "uuid"}) {
		t.Errorf("finding = %+v", f)
	}
}

// requestsOSV is an OSV stub with one PyPI advisory each against requests and pytest.
func requestsOSV() *httptest.Server {
	return httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/v1/querybatch":
			var body struct {
				Queries []osvQuery `json:"queries"`
			}

			_ = json.NewDecoder(r.Body).Decode(&body)

			results := make([]any, len(body.Queries))
			for i, q := range body.Queries {
				results[i] = map[string]any{}
				if q.Package.Name == "requests" || q.Package.Name == "pytest" {
					results[i] = map[string]any{"vulns": []any{map[string]string{"id": "GHSA-" + q.Package.Name}}}
				}
			}

			_ = json.NewEncoder(w).Encode(map[string]any{"results": results})
		case "/v1/vulns/GHSA-requests", "/v1/vulns/GHSA-pytest":
			name := strings.TrimPrefix(r.URL.Path, "/v1/vulns/GHSA-")
			_ = json.NewEncoder(w).Encode(map[string]any{
				"id":                "GHSA-" + name,
				"summary":           "advisory against " + name,
				"database_specific": map[string]string{"severity": "HIGH"},
				"affected": []any{map[string]any{
					"package": map[string]string{"name": name, "ecosystem": "PyPI"},
					"ranges":  []any{map[string]any{"events": []map[string]string{{"introduced": "0"}, {"fixed": "99.0.0"}}}},
				}},
			})
		default:
			http.NotFound(w, r)
		}
	}))
}

func findingFor(report *Report, name string) *Finding {
	for i := range report.Findings {
		if report.Findings[i].Package == name {
			return &report.Findings[i]
		}
	}

	return nil
}

// Pipfile.lock and requirements.txt are read like uv.lock: the default group is the runtime,
// develop the dev set, and a dev-only package doesn't ship.
func TestScanPipfileLockAndRequirements(t *testing.T) {
	server := requestsOSV()
	defer server.Close()

	for name, files := range map[string]map[string]string{
		"Pipfile.lock": {"Pipfile.lock": pipfileLockJSON, "app.py": "import requests\n"},
		"requirements": {"requirements.txt": "requests==2.25.0\n", "app.py": "import requests\n"},
	} {
		root := t.TempDir()
		writeFiles(t, root, files)

		report, err := Scan(Options{Directory: root, OSV: &OSV{BaseURL: server.URL, Client: server.Client()}})
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}

		if f := findingFor(report, "requests"); report.Ecosystem != EcosystemPyPI || f == nil || !f.Shipped {
			t.Errorf("%s: requests should be a shipped finding: %+v", name, report)
		}
	}

	// pytest is in develop, and never imported by the project.
	root := t.TempDir()
	writeFiles(t, root, map[string]string{"Pipfile.lock": pipfileLockJSON, "app.py": "import requests\n"})

	report, err := Scan(Options{Directory: root, OSV: &OSV{BaseURL: server.URL, Client: server.Client()}})
	if err != nil {
		t.Fatal(err)
	}

	if f := findingFor(report, "pytest"); f == nil || f.Shipped || f.Verdict != VerdictNotShipped {
		t.Errorf("a develop-only package shouldn't ship: %+v", f)
	}
}

func TestLockForManifestAndSkipReason(t *testing.T) {
	root := t.TempDir()
	writeFiles(t, root, map[string]string{
		"a/Pipfile.lock": "{}", "a/Pipfile": "", "b/yarn.lock": "", "b/package.json": "{}",
		"c/package.json": "{}", "d/requirements.txt": "requests==1.0\n",
	})

	for manifest, want := range map[string]string{
		"a/Pipfile.lock":     "a/Pipfile.lock",
		"a/Pipfile":          "a/Pipfile.lock",
		"b/yarn.lock":        "b/yarn.lock",
		"b/package.json":     "b/yarn.lock", // no package-lock.json beside it, so the yarn.lock
		"d/requirements.txt": "d/requirements.txt",
		"c/package.json":     "",
	} {
		got := lockForManifest(root, manifest)
		if want != "" {
			want = filepath.Join(root, filepath.FromSlash(want))
		}

		if got != want {
			t.Errorf("lockForManifest(%q) = %q, want %q", manifest, got, want)
		}
	}

	if reason := skipReason(root, "c/package.json"); !strings.Contains(reason, "npm install or yarn install") {
		t.Errorf("reason = %q", reason)
	}
}
