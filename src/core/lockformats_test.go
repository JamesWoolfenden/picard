const pipfileLockJSON = `{
  "_meta": {"requires": {"python_version": "3.9"}},
  "default": {
    "Requests": {"version": "==2.25.0"},
    "urllib3": {"version": "==1.26.5"},
    "mylib": {"git": "https://github.com/x/mylib.git", "ref": "abc"}
  },
  "develop": {
    "pytest": {"version": "==6.2.0"}
  }
}`

func TestReadPipfileLock(t *testing.T) {
	path := filepath.Join(t.TempDir(), "Pipfile.lock")
	if err := os.WriteFile(path, []byte(pipfileLockJSON), 0o600); err != nil {
		t.Fatal(err)
	}

	lock, err := ReadPipfileLock(path)
	if err != nil {
		t.Fatal(err)
	}

	if lock.Ecosystem != EcosystemPyPI || lock.MinPython != "3.9" {
		t.Errorf("lock = %+v", lock)
	}

	// Names are normalized, the git install (no version) is left out, develop is the dev set.
	if !reflect.DeepEqual(lock.Direct, []string{"requests", "urllib3"}) || !reflect.DeepEqual(lock.DevDirect, []string{"pytest"}) {
		t.Errorf("direct %v, dev %v", lock.Direct, lock.DevDirect)
	}

	if got := lock.Packages["requests"].Version; got != "2.25.0" {
		t.Errorf("requests version = %q", got)
	}

	if _, ok := lock.Packages["mylib"]; ok {
		t.Error("a versionless git entry should not be a locked package")
	}
}

func TestReadRequirements(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "requirements.txt")
	text := "# pinned\n-r base.txt\n--index-url https://example.com/simple\n" +
		"requests[security]==2.25.0 ; python_version >= \"3.6\"\n" +
		"Flask_Cors==3.0.9 \\\n    --hash=sha256:abc\n" +
		"aiohttp==3.9.1  # the http client\n" +
		"numpy>=1.20\nsix\n"

	if err := os.WriteFile(path, []byte(text), 0o600); err != nil {
		t.Fatal(err)
	}

	lock, err := ReadRequirements(path)
	if err != nil {
		t.Fatal(err)
	}

	got := map[string]string{}
	for name, p := range lock.Packages {
		got[name] = p.Version
	}

	want := map[string]string{"requests": "2.25.0", "flask-cors": "3.0.9", "aiohttp": "3.9.1"}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("packages = %v, want %v (ranges and bare names aren't locked)", got, want)
	}

	if len(lock.Direct) != 3 || len(lock.DevDirect) != 0 {
		t.Errorf("direct %v, dev %v", lock.Direct, lock.DevDirect)
	}

	// A dev-named file is the dev set.
	dev := filepath.Join(dir, "requirements-dev.txt")
	if err := os.WriteFile(dev, []byte("pytest==6.2.0\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	if lock, err = ReadRequirements(dev); err != nil || len(lock.Direct) != 0 || len(lock.DevDirect) != 1 {
		t.Errorf("dev file: %+v, %v", lock, err)
	}

	// A file that pins nothing is an error, not a clean scan.
	loose := filepath.Join(dir, "loose.txt")
	if err := os.WriteFile(loose, []byte("numpy>=1.20\nsix\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	if _, err := ReadRequirements(loose); err == nil || !strings.Contains(err.Error(), "pins no versions") {
		t.Errorf("unpinned file: err = %v", err)
	}
}

