const demoManifest = `{"name":"demo-ui","dependencies":{"@scope/kit":"^1.2.0"},"devDependencies":{"vitest":"^1.0.0"}}`

func TestReadYarnLock(t *testing.T) {
	for name, lockText := range map[string]string{"classic": yarnClassicLock, "berry": yarnBerryLock} {
		dir := t.TempDir()
		writeFiles(t, dir, map[string]string{"yarn.lock": lockText, "package.json": demoManifest})

		lock, err := ReadYarnLock(filepath.Join(dir, "yarn.lock"), dir)
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}

		if lock.Ecosystem != EcosystemNPM || lock.Project != "demo-ui" {
			t.Errorf("%s: lock = %+v", name, lock)
		}

		if !reflect.DeepEqual(lock.Direct, []string{"@scope/kit"}) || !reflect.DeepEqual(lock.DevDirect, []string{"vitest"}) {
			t.Errorf("%s: direct %v, dev %v", name, lock.Direct, lock.DevDirect)
		}

		// Both ms specifiers resolve to the one install; edges are resolved through the specifiers.
		if got := lock.Packages["ms"].Version; got != "2.1.3" {
			t.Errorf("%s: ms = %q", name, got)
		}

		if want := []string{"ms@2.1.3", "uuid@9.0.1"}; !reflect.DeepEqual(lock.Nodes["vitest@1.0.0"], want) {
			t.Errorf("%s: vitest edges = %v, want %v", name, lock.Nodes["vitest@1.0.0"], want)
		}

		if want := []string{"@scope/kit@1.2.0", "vitest@1.0.0"}; !reflect.DeepEqual(lock.RootNodes, want) {
			t.Errorf("%s: root nodes = %v, want %v", name, lock.RootNodes, want)
		}
	}
}

